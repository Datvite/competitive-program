const int MOD = 1e9 + 7;
int add(int a, int b)
{
    return (a + b) % MOD;
}
int sub(int a, int b)
{
    return ((a - b) % MOD + MOD) % MOD;
}
int mul(int a, int b)
{
    return ((a % MOD) * (b % MOD)) % MOD;
}
int n, k, a[N], dp[N][N];
void solve()
{
    int summin = k * (k + 1) / 2;
    int lim = n - summin;
    dp[0][0] = 1;
    for (int i = 1; i <= k; i++)
    {
        for (int j = 0; j <= lim; j++)
        {
            dp[i][j] = dp[i - 1][j];
            if (j >= i)
            {
                dp[i][j] = add(dp[i][j], dp[i][j - i]);
            }
        }
    }
    cout << dp[k][lim] << endl;
}
