int a, b, cur, ans = 0;
void solve()
{
    cur = __gcd(a, b);
    for (int i = 1; i * i <= cur; i++)
    {
        if (cur % i == 0)
        {
            if (a % i == 0 && b % (3 * i) == 0)
                ans += i;
            if (i * i != cur)
            {
                int j = cur / i;
                if (a % j == 0 && b % (3 * j) == 0)
                    ans += j;
            }
        }
    }
    cout << ans << endl;
}
