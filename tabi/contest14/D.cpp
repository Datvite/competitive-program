using namespace std;
const int N = 1e6 + 69;
const int BASE = 256;
const int MOD = 1e9 + 7;
int add(int a, int b)
{
    return (a + b) % MOD;
}
int sub(int a, int b)
{
    return ((a - b) % MOD + MOD) % MOD;
}
int mul(int a, int b)
{
    return ((a % MOD) * (b % MOD)) % MOD;
}
int n, a[N], q, tree[N * 4];
string str;
void update(int id, int l, int r, int pos, int val)
{
    if (pos < l || r < pos)
        return;
    if (l == r)
    {
        tree[id] = val;
        return;
    }
    int mid = (l + r) / 2;
    update(id * 2, l,mid, pos, val);
    update(id * 2 + 1, mid + 1,r, pos, val);
    tree[id] = tree[id * 2] | tree[id * 2 + 1];
}
int get(int id, int l, int r, int u, int v)
{
    if (r < u || l > v)
        return 0;
    if (u <= l && r <= v)
        return tree[id];
    int mid = (l + r) / 2;
    return get(id * 2, l, mid, u, v) |
           get(id * 2 + 1, mid + 1, r, u, v);
}
void solve()
{
    for (int i = 1; i <= n; i++)
        update(1, 1, n, i, 1 << (str[i] - 'a'));
    while(q--)
    {
        int t;
        cin >> t;
        if (t == 1)
        {
            char ch;
            int x;
            cin >> x >> ch;
            update(1, 1, n, x, 1 << (ch - 'a'));
        }
        else
        {
            int l, r;
            cin >> l >> r;
            cout << __builtin_popcount(get(1, 1, n, l, r)) << endl;
        }
    }
}
main()
{
    skibidi;
    file("");
    cin >> str;
    n = str.size();
    str = ' ' + str;
    cin >> q;
    solve();
}
