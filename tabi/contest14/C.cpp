using namespace std;
const int N = 1e6 + 69;
const int BASE = 256;
const int MOD = 1e9 + 7;
int add(int a, int b)
{
    return (a + b) % MOD;
}
int sub(int a, int b)
{
    return ((a - b) % MOD + MOD) % MOD;
}
int mul(int a, int b)
{
    return ((a % MOD) * (b % MOD)) % MOD;
}
int n, a[N], cnt[N], cnt2[N], bit[N], ans = 0;
int mp[N];
vector<int> v;
void update(int i)
{
    for(; i <= n; i += i & -i)
        bit[i]++;
}

int get(int i)
{
    int s=0;
    for(; i > 0; i -= i & -i)
        s+=bit[i];
    return s;
}
void solve()
{
    for (int i = 1; i <= n; i++)
    {
        cin >> a[i];
        v.push_back(a[i]);
    }
    sort(v.begin(), v.end());
    v.erase(unique(v.begin(), v.end()), v.end());
    for (int i = 1; i <= n; i++)
    {
        a[i] = lower_bound(v.begin(), v.end(), a[i]) - v.begin() + 1;
    }
    for (int i = n; i >= 1; i--)
    {
        mp[a[i]]++;
        cnt[i] = mp[a[i]];
    }
    for (int i = n; i >= 1; i--)
        mp[a[i]] = 0;
    for(int i = 1; i <= n; i++)
    {
        mp[a[i]]++;
        cnt2[i] = mp[a[i]];
    }
    for(int i = n; i >= 1; i--){
        ans += get(cnt2[i] - 1);
        update(cnt[i]);
    }
    cout << ans;
}
main()
{
    skibidi;
    file("");
    cin >> n;
    solve();
}
