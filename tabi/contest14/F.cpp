#define int long long
#define fi first
#define se second
#define ii pair<int, int>
#define iii pair<int, ii>
#define On(mask, pos) (mask | (1LL << pos))
#define Off(mask, pos) (mask ^ (1LL << pos))
#define endl "\n"
using namespace std;
const int N = 1 << 18;
const int BASE = 256;
const int MOD = 1e9 + 7;
int add(int a, int b)
{
    return (a + b) % MOD;
}
int sub(int a, int b)
{
    return ((a - b) % MOD + MOD) % MOD;
}
int mul(int a, int b)
{
    return ((a % MOD) * (b % MOD)) % MOD;
}
int n, m, a[N], u[N], v[N], w[N], dp[N], endd[N];
int dist[N];
priority_queue<pair<int, int>, vector<pair<int, int>>, greater<pair<int, int>>> q;
vector<pair<int, int>> g[N];
void dijk(int S)
{
    for (int i = 1; i <= n; i++)
        dist[i] = 1e9;
    dist[S] = 0;
    q.push({dist[S], S});
    while (!q.empty())
    {
        int u = q.top().se, cost = q.top().fi;
        q.pop();
        if (cost > dist[u])
            continue;
        for (auto e : g[u])
        {
            int v = e.fi, w = e.se;
            if (dist[v] > dist[u] + w)
            {
                dist[v] = dist[u] + w;
                q.push({dist[v], v});
            }
        }
    }
}
void solve()
{
    for (int i = 1; i <= m; i++)
    {
        cin >> u[i] >> v[i] >> w[i];
        g[u[i]].push_back({v[i], w[i]});
        g[v[i]].push_back({u[i], w[i]});
    }
    dijk(1);
    for (int i = 1; i <= 1 << n; i++)
        dp[i] = 1e18;
    dp[1] = 0;
    for (int i = 1; i <= 1 << n; i++)
    {
        for (int j = 1; j <= m; j++)
        {
            if (i & (1 << (u[j] - 1)))
            {
                if (dp[i | (1 << (v[j] - 1))] > dp[i] + w[j])
                {
                    dp[i | (1 << (v[j] - 1))] = dp[i] + w[j];
                    endd[i | (1 << (v[j] - 1))] = v[j];
                }
            }
        }
    }
    cout << dist[endd[(1 << n) - 1]] + dp[(1 << n) - 1];
}
main()
{
    skibidi;
    file("");
    cin >> n >> m;
    solve();
}
