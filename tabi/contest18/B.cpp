using namespace std;
const int N = 1e6 + 69;
const int BASE = 256;
const int MOD = 1e9 + 7;
int add(int a, int b)
{
    return (a + b) % MOD;
}
int sub(int a, int b)
{
    return ((a - b) % MOD + MOD) % MOD;
}
int mul(int a, int b)
{
    return ((a % MOD) * (b % MOD)) % MOD;
}
int n, m, ans = 0, a[N], maxn = 0;
vector<int> v1, v2;
void ql(int id, int sum)
{
    if (id > n / 2)
    {
        v1.push_back(sum % m);
        ans = max(ans, sum % m);
        return;
    }
    ql(id + 1, sum + a[id]);
    ql(id + 1, sum);
}
void ql2(int id, int sum)
{
    if (id > n)
    {
        v2.push_back(sum % m);
        ans = max(ans, sum % m);
        maxn = max(maxn, sum % m);
        return;
    }
    ql2(id + 1, sum + a[id]);
    ql2(id + 1, sum);
}
void solve()
{
    for (int i = 1; i <= n; i++)
        cin >> a[i];
    ql(1, 0);
    ql2(n / 2 + 1, 0);
    sort(v1.begin(), v1.end());
    sort(v2.begin(), v2.end());
    for (auto x : v1)
    {
        int tmp = lower_bound(v2.begin(), v2.end(), m - x) - v2.begin();
        if (tmp != 0)
            ans = max(ans, (x + v2[tmp - 1]) % m);
        else 
            ans = max(ans, (x + maxn) % m);
    }
    cout << ans;
}
main()
{
    skibidi;
    file("");
    cin >> n >> m;
    solve();
}
