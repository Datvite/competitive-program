#define On(mask, pos) (mask | (1LL << pos))
#define Off(mask, pos) (mask ^ (1LL << pos))
#define endl "\n"
using namespace std;
const int N = 1e6 + 69;
const int BASE = 256;
const int MOD = 1e9 + 7;
int add(int a, int b)
{
    return (a + b) % MOD;
}
int sub(int a, int b)
{
    return ((a - b) % MOD + MOD) % MOD;
}
int mul(int a, int b)
{
    return ((a % MOD) * (b % MOD)) % MOD;
}
int n, a[N], pos[N];
vector<int> adj[N], bfsid;
bool vis[N];
void bfs(int s)
{
    queue<int> q;
    q.push(1);
    vis[1] = true;
    while (!q.empty())
    {
        int u = q.front();
        q.pop();
        bfsid.push_back(u);
        for (int v : adj[u])
        {
            if (!vis[v])
            {
                vis[v] = true;
                q.push(v);
            }
        }
    }
}
bool cmp(int x, int y)
{
    return pos[x] < pos[y];
}
void solve()
{
    for (int i = 1; i < n; i++)
    {
        int u, v;
        cin >> u >> v;
        adj[u].push_back(v);
        adj[v].push_back(u);
    }
    for (int i = 1; i <= n; i++)
    {
        cin >> a[i];
        pos[a[i]] = i;
    }
    for (int i = 1; i <= n; i++)
        sort(adj[i].begin(), adj[i].end(), cmp);
    bfs(1);
    if (a[1] != 1)
    {
        cout << "NO" << endl;
        return;
    }
    for (int i = 1; i <= n; i++)
    {
        if (bfsid[i - 1] != a[i])
        {
            cout << "NO";
            return;
        }
    }
    cout << "YES";
}
main()
{
    skibidi;
    file("");
    cin >> n;
    solve();
}
