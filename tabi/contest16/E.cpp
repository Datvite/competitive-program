#define int long long
#define fi first
#define se second
#define ii pair<int, int>
#define iii pair<int, ii>
#define On(mask, pos) (mask | (1LL << pos))
#define Off(mask, pos) (mask ^ (1LL << pos))
#define endl "\n"
using namespace std;
const int N = 1e6 + 69;
const int BASE = 256;
const int MOD = 1e9 + 7;
int add(int a, int b)
{
    return (a + b) % MOD;
}
int sub(int a, int b)
{
    return ((a - b) % MOD + MOD) % MOD;
}
int mul(int a, int b)
{
    return ((a % MOD) * (b % MOD)) % MOD;
}
int dx[8] = {-1, -1, -1, 0, 0, 1, 1, 1};
int dy[8] = {-1, 0, 1, -1, 1, -1, 0, 1};
int n, x0, y00, x1, y11;
map<int, set<int>> mp;
queue<iii> q;
void solve()
{
    for (int i = 1; i <= n; i++)
    {
        int r, a, b;
        cin >> r >> a >> b;
        for (int j = a; j <= b; j++)
        {
            mp[r].insert(j);
        }
    }
    q.push({0, {x0, y00}});
    while (!q.empty())
    {
        iii to = q.front();
        q.pop();
        int dist = to.fi;
        int x = to.se.fi;
        int y = to.se.se;
        if (x == x1 && y == y11)
        {
            cout << dist << endl;
            return;
        }
        for (int i = 0; i < 8; i++)
        {
            int nx = x + dx[i];
            int ny = y + dy[i];
            if (mp.find(nx) != mp.end() && mp[nx].find(ny) != mp[nx].end())
            {
                mp[nx].erase(ny);
                q.push({dist + 1, {nx, ny}});
            }
        }
    }
    cout << "-1" << endl;
}
main()
{
    skibidi;
    file("");
    cin >> x0 >> y00 >> x1 >> y11 >> n;
    solve();
}
