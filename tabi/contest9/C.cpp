using namespace std;
const int N = 1e6 + 69;
const int BASE = 256;
const int MOD = 1e9 + 7;
//im gay
int add(int a, int b)
{
    return (a + b) % MOD;
}
int sub(int a, int b)
{
    return ((a - b) % MOD + MOD) % MOD;
}
int mul(int a, int b)
{
    return ((a % MOD) * (b % MOD)) % MOD;
}
int t, n, ans = 0, sum = 0, dp[N];
ii a[N];
void solve()
{
    ans = 0;
    sum = 0;
    cin >> n;
    for (int i = 1; i <= n; i++)
        cin >> a[i].fi;
    for (int i = 1; i <= n; i++)
    {
        cin >> a[i].se;
        sum += a[i].se;
    }
    for (int i = 1; i <= n; i++)
        dp[i] = 0;
    for (int i = 1; i <= n; i++)
    {
        dp[i] = a[i].se;
        for (int j = 1; j < i; j++)
            if (a[j].fi <= a[i].fi)
                dp[i] = max(dp[i], dp[j] + a[i].se);
        ans = max(ans, dp[i]);
    }
    cout << sum - ans << endl;
}
main()
{
    skibidi;
    file("");
    cin >> t;
    while (t--)
        solve();
}
