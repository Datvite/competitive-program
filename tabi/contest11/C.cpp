#define int long long
#define fi first
#define se second
#define ii pair<int, int>
#define iii pair<int, ii>
#define On(mask, pos) (mask | (1LL << pos))
#define Off(mask, pos) (mask ^ (1LL << pos))
#define endl "\n"
using namespace std;
const int N = 1e6 + 69;
const int BASE = 256;
const int MOD = 1e9 + 7;
int add(int a, int b)
{
    return (a + b) % MOD;
}
int sub(int a, int b)
{
    return ((a - b) % MOD + MOD) % MOD;
}
int mul(int a, int b)
{
    return ((a % MOD) * (b % MOD)) % MOD;
}
int t, n, m, a[N], b[N], suma = 0, sumb = 0;
priority_queue<int> qa, qb;
void solve()
{
    cin >> n >> m;
    suma = 0;
    sumb = 0;
    while (!qa.empty())
        qa.pop();
    while (!qb.empty())
        qb.pop();
    for (int i = 1; i <= n; i++)
    {
        cin >> a[i];
        qa.push(a[i]);
        suma += a[i];
    }
    for (int i = 1; i <= m; i++)
    {
        cin >> b[i];
        qb.push(b[i]);
        sumb += b[i];
    }
    if (suma != sumb)
    {
        cout << "NO" << endl;
        return;
    }
    while (!qb.empty())
    {
        if (qa.empty())
        {
            cout << "NO" << endl;
            return;
        }
        int x = qb.top();
        qb.pop();
        int y = qa.top();
        if (x == y)
            qa.pop();
        else if (x > y)
        {
            if (x == 1)
            {
                cout << "NO" << endl;
                return;
            }
            qb.push(x / 2);
            qb.push(x - x / 2);
        }
        else
        {
            cout << "NO" << endl;
            return;
        }
    }
    if (qa.empty())
        cout << "YES" << endl;
    else
        cout << "NO" << endl;
}
main()
{
    skibidi;
    file("");
    cin >> t;
    while (t--)
        solve();
}
