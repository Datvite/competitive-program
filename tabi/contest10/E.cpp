using namespace std;
const int N = 1e6 + 69;
const int BASE = 256;
const int MOD = 1e9 + 7;
int add(int a, int b)
{
    return (a + b) % MOD;
}
int sub(int a, int b)
{
    return ((a - b) % MOD + MOD) % MOD;
}
int mul(int a, int b)
{
    return ((a % MOD) * (b % MOD)) % MOD;
}
int t, x, y, a, b;
bool check(double mid)
{
    int cur1 = max(0.0, ceil((mid * a - y) / (a - b)));
    int cur2 = min(mid, floor((x - mid * b) / (a - b)));
    return cur1 <= cur2;
}
void solve()
{
    cin >> x >> y >> a >> b;
    int l = 0, r = 1e9, res = 0;
    if (a == b)
    {
        cout << min(x / a, y / a) << endl;
        return;
    }
    if (b > a)
        swap(a, b);
    while (l <= r)
    {
        int mid = (l + r) / 2;
        if (check(mid))
        {
            res = mid;
            l = mid + 1;
        }
        else
            r = mid - 1;
    }
    cout << res << endl;
}
main()
{
    skibidi;
    file("");
    cin >> t;
    while (t--)
        solve();
}
