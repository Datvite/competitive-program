struct Sieve
{
    int n;
    std::vector<int> min_prime;
    std::vector<int> primes;

    Sieve(int n) : n(n)
    {
        min_prime.assign(n + 1, 0);
        for (int i = 2; i <= n; i++)
        {
            if (min_prime[i] == 0)
            {
                min_prime[i] = i;
                primes.push_back(i);
            }
            for (int p : primes)
            {
                if (p > min_prime[i] || i * p > n)
                    break;
                min_prime[i * p] = p;
            }
        }
    }

    bool is_prime(int x)
    {
        if (x < 2)
        {
            return false;
        }
        return min_prime[x] == x;
    }
};

const int max_val = 1e4;

struct Dijkstra
{
    int n;
    std::vector<std::vector<std::pair<int, long long>>> adj;
    std::vector<long long> dist;
    const long long INF = 1e18;

    Dijkstra(int n)
    {
        this->n = n;
        adj.resize(n + 7);
        dist.assign(n + 7, INF);
    }

    void add_edge(int u, int v, long long w)
    {
        adj[u].push_back({v, w});
        adj[v].push_back({u, w});
    }

    void run(int s)
    {
        dist.assign(n + 7, INF);
        std::priority_queue<std::pair<long long, int>, std::vector<std::pair<long long, int>>, std::greater<std::pair<long long, int>>> pq;

        dist[s] = 0;
        pq.push({0, s});

        while (!pq.empty())
        {
            auto [d, u] = pq.top();
            pq.pop();

            if (d > dist[u])
                continue;

            for (auto [v, w] : adj[u])
            {
                if (dist[u] + w < dist[v])
                {
                    dist[v] = dist[u] + w;
                    pq.push({dist[v], v});
                }
            }
        }
    }
};

int ans[max_val + 7];

void solve()
{
    std::cin >> n;
    Sieve sieve(max_val);

    for (int i = 1; i <= n; i++)
    {
        int x;
        std::cin >> x;
        freq[x]++;
    }

    Dijkstra dijk(max_val);

    for (int i = 1; i <= max_val; i++)
    {
        for (int p : sieve.primes)
        {
            if (i * p > max_val)
            {
                break;
            }
            dijk.add_edge(i, i * p, 1);
        }
    }

    for (int i = 1; i <= max_val; i++)
    {
        if (freq[i])
        {
            dijk.run(i);

            for (int j = 1; j <= max_val; j++)
            {
                if (dijk.dist[j] != dijk.INF)
                {
                    ans[j] += dijk.dist[j] * freq[i];
                }
            }
        }
    }

    int res = INF;
    int pos = 1;

    for (int j = 1; j <= max_val; j++)
    {
        if (ans[j] < res)
        {
            res = ans[j];
            pos = j;
        }
    }

    std::cout << res << " " << pos << "\n";
}

