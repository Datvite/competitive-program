using namespace std;
const int N = 1e6 + 69;
const int BASE = 256;
const int MOD = 1e9 + 7;
int add(int a, int b)
{
    return (a + b) % MOD;
}
int sub(int a, int b)
{
    return ((a - b) % MOD + MOD) % MOD;
}
int mul(int a, int b)
{
    return ((a % MOD) * (b % MOD)) % MOD;
}
int n, q, a[N], par[N], par2[N], nt[N], sz[N];
int acs(int x)
{
    if (par[x] == x)
        return x;
    return par[x] = acs(par[x]);
}
int acs2(int x)
{
    if (nt[x] == x)
        return x;
    return nt[x] = acs2(nt[x]);
}
void join(int x, int y)
{
    x = acs(x);
    y = acs(y);
    if (x != y)
        {
            if (sz[x] < sz[y])
                swap(x, y);
            par[y] = x;
            sz[x] += sz[y];
        }
}
void solve()
{
    for (int i = 1; i <= n; i++)
        {
            par[i] = i;
            sz[i] = 1;
        }
    for (int i = 1; i <= n; i++)
        nt[i] = i;
    while (q--)
    {
        int ty, x, y;
        cin >> ty >> x >> y;
        if (ty == 1)
            join(x, y);
        else if (ty == 2)
        {
            x = acs2(x);
            while (x < y)
            {
                join(x, x + 1);
                int tmp = acs2(x + 1);
                nt[x] = tmp;
                x = tmp;
            }
        }
        else
        {
            if (acs(x) == acs(y))
                cout << "YES" << endl;
            else
                cout << "NO" << endl;
        }
    }
}
main()
{
    skibidi;
    file("gopso");
    cin >> n >> q;
    solve();
}
