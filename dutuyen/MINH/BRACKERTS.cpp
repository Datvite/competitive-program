int n, t, depth[N], nxt[N], ans = 0;
void solve()
{
    string str;
    ans = 0;
    cin >> str;
    n = str.size();
    str = ' ' + str;
    for (int i = 1; i <= n; i++)
    {
        if (str[i] == '(')
            depth[i] = depth[i - 1] + 1;
        else
            depth[i] = depth[i - 1] - 1;
    }
    int cur = n + 1;
    for (int i = n; i >= 1; i--)
    {
        if (depth[i] == 0)
            cur = i;
        ans += cur + 1;
    }
    cout << ans + 1 << endl;
}
