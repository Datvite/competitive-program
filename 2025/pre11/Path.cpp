using namespace std;
const int N = 307;
const int BASE = 256;
const int MOD = 1e9 + 7;
int add(int a, int b)
{
    return (a + b) % MOD;
}
int sub(int a, int b)
{
    return ((a - b) % MOD + MOD) % MOD;
}
int mul(int a, int b)
{
    return ((a % MOD) * (b % MOD)) % MOD;
}
int n, a[N][N], dp[N][N][N];
void solve()
{
    for (int i = 1; i <= n; i++)
        for (int j = 1; j <= n; j++)
            cin >> a[i][j];
    for (int k = 0; k <= 2 * n; k++)
        for (int i = 0; i <= n; i++)
            for (int j = 0; j <= n; j++)
                dp[k][i][j] = -1e18;
    dp[2][1][1] = a[1][1];
    for (int k = 2; k <= 2 * n; k++)
    {
        for (int i1 = 1; i1 <= n; i1++)
        {
            int j1 = k - i1;
            if (j1 < 1 || j1 > n)
                continue;
            for (int i2 = 1; i2 <= n; i2++)
            {
                int j2 = k - i2;
                if (j2 < 1 || j2 > n)
                    continue;
                int best = -1e18;
                best = max(best, dp[k - 1][i1][i2]);
                if (i1 > 1)
                    best = max(best, dp[k - 1][i1 - 1][i2]);
                if (i2 > 1)
                    best = max(best, dp[k - 1][i1][i2 - 1]);
                if (i1 > 1 && i2 > 1)
                    best = max(best, dp[k - 1][i1 - 1][i2 - 1]);
                if (best == -1e18)
                    continue;
                int add = a[i1][j1];
                if (i1 != i2 || j1 != j2)
                    add += a[i2][j2];
                dp[k][i1][i2] = add + best;
            }
        }
    }
    cout << dp[2 * n][n][n] << endl;
}
main()
{
    skibidi;
    file("Path");
    cin >> n;
    solve();
}
