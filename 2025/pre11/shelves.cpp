#define int long long
#define fi first
#define se second
#define ii pair<int, int>
#define iii pair<int, ii>
#define On(mask, pos) (mask | (1LL << pos))
#define Off(mask, pos) (mask ^ (1LL << pos))
#define endl "\n"
using namespace std;
const int N = 1e6 + 69;
const int BASE = 256;
const int MOD = 1e9 + 7;
int add(int a, int b)
{
    return (a + b) % MOD;
}
int sub(int a, int b)
{
    return ((a - b) % MOD + MOD) % MOD;
}
int mul(int a, int b)
{
    return ((a % MOD) * (b % MOD)) % MOD;
}
int n, m;
pair<ii, ii> a[N];
vector<int> ans[N];
bool cmp(pair<ii, ii> x, pair<ii, ii> y)
{
    return x.fi.se < y.fi.se;
}
void solve()
{
    for (int i = 1; i <= n; i++)
    {
        int x;
        cin >> x;
        a[i] = {{a[i - 1].fi.se, a[i - 1].fi.se + x}, {1, i}};
    }
    for (int i = n + 1; i <= n + m; i++)
    {
        int x;
        cin >> x;
        if (i == n + 1)
            a[i] = {{0, x}, {2, i}};
        else
            a[i] = {{a[i - 1].fi.se, a[i - 1].fi.se + x}, {2, i}};
    }
    sort(a + 1, a + n + m + 1, cmp);
    int cur = a[1].fi.se;
    ans[a[1].se.fi].push_back(a[1].se.se);

    // khác đéo chi mấy bài xếp lịch sao cho ko trùng nhau
    
    for (int i = 1; i <= n + m; i++)
    {
        if (a[i].fi.fi >= cur)
        {
            cur = a[i].fi.se;
            ans[a[i].se.fi].push_back(a[i].se.se);
        }
    }
    cout << ans[1].size() << " " << ans[2].size() << endl;
    for (auto x : ans[1])
        cout << x << " ";
    cout << endl;
    for (auto x : ans[2])
        cout << x - n << " ";
}
main()
{
    skibidi;
    file("");
    cin >> n >> m;
    solve();
}
