const int N = 3e3 + 69;
const int BASE = 256;
const int MOD = 1e9 + 7;
int add(int a, int b)
{
    return (a + b) % MOD;
}
int sub(int a, int b)
{
    return ((a - b) % MOD + MOD) % MOD;
}
int mul(int a, int b)
{
    return ((a % MOD) * (b % MOD)) % MOD;
}
int n, m, a[N], dp[N][N], trace[N][N];
string s1, s2;
void solve()
{
    // LCS algorithm
    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= m; j++)
        {
            if (s1[i] == s2[j])
                {
                    dp[i][j] = dp[i - 1][j - 1] + 1;
                    trace[i][j] = 1;
                }
            else
                {
                    dp[i][j] = max(dp[i - 1][j], dp[i][j - 1]);
                    trace[i][j] = 2;
                }
        }
    }
    //cout << dp[n][m];
    // trace
    vector<char> res;
    int i = n, j = m;
    while (i > 0 && j > 0)
    {
        if (trace[i][j] == 1)
        {
            res.push_back(s1[i]);
            i--;
            j--;
        }
        else if (trace[i][j] == 2)
        {
            if (dp[i - 1][j] >= dp[i][j - 1])
                i--;
            else
                j--;
        }
    }
    reverse(res.begin(), res.end());
    cout << endl;
    for (char c : res)
        cout << c;
}
