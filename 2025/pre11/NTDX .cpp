int add(int a, int b)
{
    return (a + b) % MOD;
}
int sub(int a, int b)
{
    return ((a - b) % MOD + MOD) % MOD;
}
int mul(int a, int b)
{
    return ((a % MOD) * (b % MOD)) % MOD;
}
int l, r, a[N], ans = 0;
bool isPrime(int n)
{
    if (n < 2)
        return 0;
    if (n == 2)
        return 1;
    if (n % 2 == 0)
        return 0;
    for (int i = 3; i * i <= n; i += 2)
        if (n % i == 0)
            return 0;
    return 1;
}
int create(int half, bool odd)
{
    int res = half;
    if (odd)
        half /= 10;
    while (half > 0)
    {
        res = res * 10 + half % 10;
        half /= 10;
    }
    return res;
}
void solve()
{
    bool ok = 0;
    for (int len = 1; len <= 9; len++)
    {
        if (len % 2 == 0 && len != 2)
            continue;
        int start = pow(10, (len - 1) / 2);
        int finish = pow(10, (len + 1) / 2);
        for (int half = start; half < finish; half++)
        {
            int pal = create(half, len % 2);
            if (pal > r)
                break;
            if (pal >= l && isPrime(pal))
                ans++;
        }
    }
    cout << ans;
}
