using namespace std;
const int N = 1e6 + 69;
const int BASE = 256;
const int MOD = 1e9 + 7;
int add(int a, int b)
{
    return (a + b) % MOD;
}
int sub(int a, int b)
{
    return ((a - b) % MOD + MOD) % MOD;
}
int mul(int a, int b)
{
    return ((a % MOD) * (b % MOD)) % MOD;
}
int n, m, a[N], b[N], dp[N], trace[N];
vector<int> ans;
void solve()
{
    for (int i = 1; i <= n; i++)
        cin >> a[i];
    for (int j = 1; j <= m; j++)
        cin >> b[j];
    // LCIS algorithm
    for (int i = 1; i <= n; i++)
    {
        int current = 0, last = 0;
        for (int j = 1; j <= m; j++)
        {
            if (a[i] == b[j])
            {
                if (current + 1 > dp[j])
                {
                    dp[j] = current + 1;
                    trace[j] = last;
                }
            }
            if (a[i] > b[j])
            {
                if (dp[j] > current)
                {
                    current = dp[j];
                    last = j;
                }
            }
        }
    }
    int res = 0, id = -1;
    for (int j = 1; j <= m; j++)
        if (dp[j] > res)
        {
            res = dp[j];
            id = j;
        }
    cout << res;
    do
    {
        ans.push_back(b[id]);
        id = trace[id];
    } while (id != 0);
    reverse(ans.begin(), ans.end());
    cout << endl;
    for (int x : ans)
        cout << x << " ";
}
main()
{
    skibidi;
    file("");
    cin >> n >> m;
    solve();
}
