using namespace std;
const int N = 1e6 + 69;
const int BASE = 256;
const int MOD = 1e9 + 7;
int add(int a, int b)
{
    return (a + b) % MOD;
}
int sub(int a, int b)
{
    return ((a - b) % MOD + MOD) % MOD;
}
int mul(int a, int b)
{
    return ((a % MOD) * (b % MOD)) % MOD;
}
int n, a[N], min1 = 1e18, min2 = 1e18, max1 = -1e18, max2 = -1e18;
void solve()
{
    for (int i = 1; i <= n; i++)
    {
        cin >> a[i];
        if (a[i] < min1)
        {
            min2 = min1;
            min1 = a[i];
        }
        else if (a[i] < min2)
        {
            min2 = a[i];
        }
        if (a[i] > max1)
        {
            max2 = max1;
            max1 = a[i];
        }
        else if (a[i] > max2)
        {
            max2 = a[i];
        }
    }
    cout << max(abs(max1 + max2), abs(min1 + min2));
}
main()
{
    skibidi;
    file("WEI");
    cin >> n;
    solve();
}
