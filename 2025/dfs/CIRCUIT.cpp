#define int long long
#define fi first
#define se second
#define ii pair<int, int>
#define iii pair<int, ii>
#define On(mask, pos) (mask | (1LL << pos))
#define Off(mask, pos) (mask ^ (1LL << pos))
#define endl "\n"
using namespace std;
const int N = 1e6 + 69;
const int BASE = 256;
const int MOD = 1e9 + 7;
int add(int a, int b)
{
    return (a + b) % MOD;
}
int sub(int a, int b)
{
    return ((a - b) % MOD + MOD) % MOD;
}
int mul(int a, int b)
{
    return ((a % MOD) * (b % MOD)) % MOD;
}
int n, m, a[N], mark = 0;
vector<int> ans;
vector<ii> g[N];
bool vis[N], flag[N], check = 0;
void dfs(int u)
{
    vis[u] = 1;
    flag[u] = 1;
    for (ii x : g[u])
    {
        int v = x.fi;
        int id = x.se;
        if (!vis[v])
            dfs(v);
        else if (flag[v])
        {
            check = 1;
            mark = v;
        }
        if (check)
        {
            ans.push_back(id);
            break;
        }
    }
    if (u == mark)
    {
        cout << "YES" << endl;
        reverse(ans.begin(), ans.end());
        for (auto x : ans)
            cout << x << " ";
        exit(0);
    }
    flag[u] = 0;
}
void solve()
{
    for (int i = 1; i <= m; i++)
    {
        int u, v;
        cin >> u >> v;
        g[u].push_back({v, i});
    }
    for (int i = 1; i <= n; i++)
    {
        if (!vis[i])
        {
            dfs(i);
        }
    }
    cout << "NO" << endl;
}
main()
{
    skibidi;
    file("CIRCUIT");
    cin >> n >> m;
    solve();
}
