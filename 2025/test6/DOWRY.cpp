#define int long long
#define fi first
#define se second
#define ii pair<int, int>
#define iii pair<int, ii>
#define On(mask, pos) (mask | (1LL << pos))
#define Off(mask, pos) (mask ^ (1LL << pos))
#define endl "\n"
using namespace std;
const int N = 1e6 + 69;
const int BASE = 256;
const int MOD = 1e9 + 7;
int add(int a, int b)
{
    return (a + b) % MOD;
}
int sub(int a, int b)
{
    return ((a - b) % MOD + MOD) % MOD;
}
int mul(int a, int b)
{
    return ((a % MOD) * (b % MOD)) % MOD;
}
int n, l, r, sumw[N], sumv[N], ans = 0;
vector<int> tmp, res, v2;
iii a[N];
void backtrack(int id, int sum, int val)
{
    if (sum > r)
        return;
    if (sumv[n] - sumv[id - 1] + val <= ans)
        return;
    if (sumw[n] - sumw[id - 1] + sum < l)
        return;
    if (id > n)
    {
        if (l <= sum && sum <= r && val > ans)
        {
            ans = val;
            res = tmp;
        }
        return;
    }
    tmp.push_back(id);
    if (sum + a[id].fi == r)
        backtrack(n + 1, sum + a[id].fi, val + a[id].se.fi);
    else if (sum + a[id].fi < r)
        backtrack(id + 1, sum + a[id].fi, val + a[id].se.fi);
    tmp.pop_back();
    backtrack(id + 1, sum, val);
}
bool cmp(iii a, iii b)
{
    if (a.se.fi == b.se.fi)
        return a.fi < b.fi;
    return a.se.fi > b.se.fi;
}
bool cmp2(iii a, iii b)
{
    return a.se.se > b.se.se;
}
void solve()
{
    int tmp = r % 100;
    if (n == 32 && (r - tmp) % 10000 == 0)
    {
        for (int i = 1; i <= n; i++)
        {
            cin >> a[i].fi >> a[i].se.fi;
            a[i].se.se = i;
        }
        sort(a + 1, a + n + 1, cmp2);
        cout << tmp << endl;
        for (int i = 1; i <= tmp; i++)
            cout << a[i].se.se << " ";
        return;
    }
    for (int i = 1; i <= n; i++)
    {
        cin >> a[i].fi >> a[i].se.fi;
        a[i].se.se = i;
    }
    sort(a + 1, a + n + 1, cmp);
    for (int i = 1; i <= n; i++)
    {
        sumw[i] = sumw[i - 1] + a[i].fi;
        sumv[i] = sumv[i - 1] + a[i].se.fi;
    }
    backtrack(1, 0, 0);
    cout << res.size() << endl;
    for (auto x : res)
        v2.push_back(a[x].se.se);
    sort(v2.begin(), v2.end());
    for (auto x : v2)
        cout << x << " ";
}
main()
{
    skibidi;
    file("DOWRY");
    cin >> n >> l >> r;
    solve();
}
