inline ll add(ll a, ll b)
{
    return ((a % mod + b % mod) % mod + mod) % mod;
}
inline ll mul(ll a, ll b)
{
    return ((a % mod) * (b % mod) + mod) % mod;
}
inline ll sub(ll a, ll b)
{
    return ((a % mod - b % mod) % mod + mod) % mod;
}
ll n, m, k;
bool check(ll x, vector<vector<char>> a)
{
    ll ans = 0;
    for (ll i = 1; i <= n; i++)
    {
        ll c = 0, d = 0;
        for (ll j = 1; j <= m; j++)
        {
            if (a[i][j] == 'x')
            {
                if (j <= c)
                    continue;
                else
                {
                    d++;
                    c = j + 2 * x;
                }
            }
            if (a[i][j] == '#')
            {
                c = 0;
            }
        }
        ans += d;
    }
    return ans <= k;
}
void solve()
{
    cin >> n >> m >> k;
    vector<vector<char>> a(n + 1, vector<char>(m + 1, '0'));
    for (ll i = 1; i <= n; i++)
    {
        for (ll j = 1; j <= m; j++)
        {
            cin >> a[i][j];
        }
    }
    ll l = 0, r = m, res = -1;
    while (l <= r)
    {
        ll mid = (l + r) / 2;
        if (check(mid, a))
        {
            res = mid;
            r = mid - 1;
        }
        else
            l = mid + 1;
    }
    cout << res;
}
