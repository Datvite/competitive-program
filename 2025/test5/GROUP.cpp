#define int long long
#define fi first
#define se second
#define ii pair<int, int>
#define iii pair<int, ii>
#define On(mask, pos) (mask | (1LL << pos))
#define Off(mask, pos) (mask ^ (1LL << pos))
#define endl "\n"
using namespace std;
const int N = 1e6 + 69;
const int BASE = 256;
const int MOD = 1e9 + 7;
int add(int a, int b)
{
    return (a + b) % MOD;
}
int sub(int a, int b)
{
    return ((a - b) % MOD + MOD) % MOD;
}
int mul(int a, int b)
{
    return ((a % MOD) * (b % MOD)) % MOD;
}
int n, a[N], ans = 0;
vector<iii> group;
void solve()
{
    for (int i = 1; i <= n; i++)
        cin >> a[i];
    for (int i = 1; i <= n; i++)
    {
        for (int j = i + 1; j <= n; j++)
        {
            int g = __gcd(a[i], a[j]);
            group.push_back({g, {i, j}});
        }
    }
    sort(group.begin(), group.end(), greater<iii>());
    int m = group.size();
    for (int i = 0; i < m; i++)
    {
        int g = group[i].fi;
        int u = group[i].se.fi;
        int v = group[i].se.se;
        for (int j = i + 1; j < m; j++)
        {
            int g2 = group[j].fi;
            int u2 = group[j].se.fi;
            int v2 = group[j].se.se;
            if (u != u2 && u != v2 && v != u2 && v != v2)
            {
                ans = max(ans, g + g2);
                break;
            }
        }
    }
    cout << ans << endl;
}
main()
{
    skibidi;
    file("GROUP");
    cin >> n;
    solve();
}
